export type AnimatedPixelSpriteProps = Omit<AnimatedPixelIconProps, "name" | "tone" | "pigment"> & {
  recipe: PixelRecipe;
  /** 靜止時的 16 列點陣（沒有 recipe.rest 時使用） */
  base: readonly string[];
  /** 物件本色；省略是墨色 */
  palette?: PixelPalette;
};

/** 用任意點陣與影格畫一個動態像素圖示（擴充圖示組沿用同一套觸發、影格與減少動態處理） */
export function AnimatedPixelSprite({
  recipe,
  base,
  palette,
  active,
  trigger = "parent",
  size = 16,
  title,
  ...rest
}: AnimatedPixelSpriteProps) {
  const reduce = useReducedMotion();
  const ref = useRef<SVGSVGElement>(null);
  const [hovered, setHovered] = useState(false);
  // -1 是靜止格，0 起是 frames 的索引
  const [frame, setFrame] = useState(() => (recipe.kind === "toggle" && active ? recipe.frames.length - 1 : -1));
  const last = recipe.frames.length - 1;
  const controlled = active !== undefined;

  useEffect(() => {
    if (controlled) return;
    const el = trigger === "self" ? ref.current : ref.current?.parentElement;
    if (!el) return;
    const on = () => setHovered(true);
    const off = () => setHovered(false);
    el.addEventListener("pointerenter", on);
    el.addEventListener("pointerleave", off);
    el.addEventListener("focusin", on);
    el.addEventListener("focusout", off);
    return () => {
      el.removeEventListener("pointerenter", on);
      el.removeEventListener("pointerleave", off);
      el.removeEventListener("focusin", on);
      el.removeEventListener("focusout", off);
    };
  }, [controlled, trigger]);

  const on = controlled ? Boolean(active) : hovered;

  useEffect(() => {
    const ms = 1000 / recipe.fps;
    if (recipe.kind === "toggle") {
      const target = on ? last : -1;
      if (reduce) {
        setFrame(target);
        return;
      }
      const id = setInterval(() => {
        setFrame((f) => {
          if (f === target) {
            clearInterval(id);
            return f;
          }
          return f + (f < target ? 1 : -1);
        });
      }, ms);
      return () => clearInterval(id);
    }
    if (!on || reduce) {
      setFrame(-1);
      return;
    }
    if (recipe.kind === "loop") {
      const id = setInterval(() => setFrame((f) => (f >= last ? -1 : f + 1)), ms);
      return () => clearInterval(id);
    }
    // hover：從第一格播到最後一格，再回到靜止格
    setFrame(0);
    const id = setInterval(() => {
      setFrame((f) => {
        if (f === -1 || f >= last) {
          clearInterval(id);
          return -1;
        }
        return f + 1;
      });
    }, ms);
    return () => clearInterval(id);
  }, [on, reduce, recipe, last]);

  const raw =
    frame >= 0 && frame <= last
      ? framePaths(recipe.frames[frame])
      : recipe.rest
        ? framePaths(recipe.rest)
        : framePaths(base.join("/"));
  const paths = palette && isStrokeOnly(raw) && isMixed(recipe) ? asEdge(raw) : raw;

  return (
    <svg
      ref={ref}
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
      data-state={on ? "active" : "rest"}
      data-tone={palette ? "pigment" : undefined}
      overflow="visible"
      {...rest}
    >
      {title && <title>{title}</title>}
      <PixelPathsGroup paths={paths} palette={palette} />
    </svg>
  );
}
