export type AnimatedPixelIconName = keyof typeof pixelRecipes;
export const animatedPixelIconNames = Object.keys(pixelRecipes) as AnimatedPixelIconName[];
export const pixelMotionKindOf = (name: AnimatedPixelIconName): PixelMotionKind => pixelRecipes[name].kind;

export type AnimatedPixelIconProps = Omit<SVGProps<SVGSVGElement>, "children" | "ref"> & {
  name: AnimatedPixelIconName;
  /** toggle 與 loop 用；hover 類不必傳 */
  active?: boolean;
  /** hover 類的觸發來源：parent（預設，整顆按鈕）或 self */
  trigger?: "parent" | "self";
  size?: number | string;
  title?: string;
};

const cache = new Map<string, PixelPaths>();
const decode = (row: string) => row.replace(/(\d+)(\D)/g, (_, n: string, ch: string) => ch.repeat(Number(n)));
function framePaths(frame: string) {
  let hit = cache.get(frame);
  if (!hit) {
    hit = toPixelPaths(frame.split("/").map(decode));
    cache.set(frame, hit);
  }
  return hit;
}

const query = "(prefers-reduced-motion: reduce)";
function useReducedMotion() {
  return useSyncExternalStore(
    (notify) => {
      const mq = window.matchMedia(query);
      mq.addEventListener("change", notify);
      return () => mq.removeEventListener("change", notify);
    },
    () => window.matchMedia(query).matches,
    () => false,
  );
}

export function AnimatedPixelIcon({
  name,
  active,
  trigger = "parent",
  size = 16,
  title,
  ...rest
}: AnimatedPixelIconProps) {
  const recipe: Recipe = pixelRecipes[name];
  const reduce = useReducedMotion();
  const ref = useRef<SVGSVGElement>(null);
  const [hovered, setHovered] = useState(false);
  // -1 是靜止格，0 起是 frames 的索引
  const [frame, setFrame] = useState(() => (recipe.kind === "toggle" && active ? recipe.frames.length - 1 : -1));
  const last = recipe.frames.length - 1;
  const controlled = active !== undefined;

  useEffect(() => {
    if (controlled) return;
    const el = trigger === "self" ? ref.current : ref.current?.parentElement;
    if (!el) return;
    const on = () => setHovered(true);
    const off = () => setHovered(false);
    el.addEventListener("pointerenter", on);
    el.addEventListener("pointerleave", off);
    el.addEventListener("focusin", on);
    el.addEventListener("focusout", off);
    return () => {
      el.removeEventListener("pointerenter", on);
      el.removeEventListener("pointerleave", off);
      el.removeEventListener("focusin", on);
      el.removeEventListener("focusout", off);
    };
  }, [controlled, trigger]);

  const on = controlled ? Boolean(active) : hovered;

  useEffect(() => {
    const ms = 1000 / recipe.fps;
    if (recipe.kind === "toggle") {
      const target = on ? last : -1;
      if (reduce) {
        setFrame(target);
        return;
      }
      const id = setInterval(() => {
        setFrame((f) => {
          if (f === target) {
            clearInterval(id);
            return f;
          }
          return f + (f < target ? 1 : -1);
        });
      }, ms);
      return () => clearInterval(id);
    }
    if (!on || reduce) {
      setFrame(-1);
      return;
    }
    if (recipe.kind === "loop") {
      const id = setInterval(() => setFrame((f) => (f >= last ? -1 : f + 1)), ms);
      return () => clearInterval(id);
    }
    // hover：從第一格播到最後一格，再回到靜止格
    setFrame(0);
    const id = setInterval(() => {
      setFrame((f) => {
        if (f === -1 || f >= last) {
          clearInterval(id);
          return -1;
        }
        return f + 1;
      });
    }, ms);
    return () => clearInterval(id);
  }, [on, reduce, recipe, last]);

  const paths =
    frame >= 0 && frame <= last
      ? framePaths(recipe.frames[frame])
      : recipe.rest
        ? framePaths(recipe.rest)
        : toPixelPathsCached(name);

  return (
    <svg
      ref={ref}
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
      data-icon={name}
      data-state={on ? "active" : "rest"}
      {...rest}
    >
      {title && <title>{title}</title>}
      <PixelPathsGroup paths={paths} />
    </svg>
  );
}

function toPixelPathsCached(name: PixelIconName) {
  return framePaths(pixelIcons[name].join("/"));
}
