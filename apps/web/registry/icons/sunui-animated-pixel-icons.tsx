const cache = new Map<string, PixelPaths>();
const decode = (row: string) => row.replace(/(\d+)(\D)/g, (_, n: string, ch: string) => ch.repeat(Number(n)));
function framePaths(frame: string) {
  let hit = cache.get(frame);
  if (!hit) {
    const rows = frame.split("/").map(decode);
    // 20 列的影格以 (-2, -2) 為原點，對齊 16 格的 viewBox
    hit = toPixelPaths(rows, -(rows.length - 16) / 2);
    cache.set(frame, hit);
  }
  return hit;
}

const query = "(prefers-reduced-motion: reduce)";
function useReducedMotion() {
  return useSyncExternalStore(
    (notify) => {
      const mq = window.matchMedia(query);
      mq.addEventListener("change", notify);
      return () => mq.removeEventListener("change", notify);
    },
    () => window.matchMedia(query).matches,
    () => false,
  );
}

