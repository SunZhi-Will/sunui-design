export type AnimatedPixelIconProps = Omit<SVGProps<SVGSVGElement>, "children" | "ref"> & {
  name: AnimatedPixelIconName;
  /** toggle 與 loop 用；hover 類不必傳 */
  active?: boolean;
  /** hover 類的觸發來源：parent（預設，整顆按鈕）或 self */
  trigger?: "parent" | "self";
  size?: number | string;
  title?: string;
  /** ink（預設）或 pigment（物件本色），同 PixelIcon */
  tone?: PixelTone;
  /** 指定顏色，覆蓋預設對照；傳了就視為 pigment */
  pigment?: Pigment;
};

const cache = new Map<string, PixelPaths>();
const decode = (row: string) => row.replace(/(\d+)(\D)/g, (_, n: string, ch: string) => ch.repeat(Number(n)));
function framePaths(frame: string) {
  let hit = cache.get(frame);
  if (!hit) {
    const rows = frame.split("/").map(decode);
    // 20 列的影格以 (-2, -2) 為原點，對齊 16 格的 viewBox
    hit = toPixelPaths(rows, -(rows.length - 16) / 2);
    cache.set(frame, hit);
  }
  return hit;
}

const isStrokeOnly = (paths: PixelPaths) => Object.keys(paths).every((k) => k === "#");
const mixedCache = new Map<Recipe, boolean>();
/** 同一個動畫裡有只有線的影格，也有填色的影格（空心愛心填滿） */
function isMixed(recipe: Recipe) {
  let hit = mixedCache.get(recipe);
  if (hit === undefined) {
    const all = [...(recipe.rest ? [recipe.rest] : []), ...recipe.frames].map(framePaths);
    hit = all.some(isStrokeOnly) && !all.every(isStrokeOnly);
    mixedCache.set(recipe, hit);
  }
  return hit;
}
const asEdgeCache = new WeakMap<PixelPaths, PixelPaths>();
/** 把只有線的影格當成填色圖示的邊來上色，pigment 時外框顏色才不會在播放中途跳色 */
function asEdge(paths: PixelPaths) {
  let hit = asEdgeCache.get(paths);
  if (!hit) {
    hit = { o: paths["#"] };
    asEdgeCache.set(paths, hit);
  }
  return hit;
}

const query = "(prefers-reduced-motion: reduce)";
function useReducedMotion() {
  return useSyncExternalStore(
    (notify) => {
      const mq = window.matchMedia(query);
      mq.addEventListener("change", notify);
      return () => mq.removeEventListener("change", notify);
    },
    () => window.matchMedia(query).matches,
    () => false,
  );
}

