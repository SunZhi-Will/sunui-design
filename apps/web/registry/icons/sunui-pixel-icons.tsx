export type PixelIconName = keyof typeof pixelIcons;
export const pixelIconNames = Object.keys(pixelIcons) as PixelIconName[];

export type PixelIconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  name: PixelIconName;
  /** 寬高，預設 16；用 16 的整數倍最銳利 */
  size?: number | string;
  /** 提供時圖示會被讀出；不提供時視為裝飾，aria-hidden */
  title?: string;
};

const ACCENT = "var(--sunui-icon-accent, currentColor)";
const cache = new Map<string, { ink: string; accent: string }>();

/** 把點陣轉成兩條路徑：同一列相鄰的格子合併成一段，路徑短、縮放不留縫 */
export function pixelPaths(name: PixelIconName) {
  const hit = cache.get(name);
  if (hit) return hit;
  let ink = "";
  let accent = "";
  pixelIcons[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === ".") {
        x += 1;
        continue;
      }
      let end = x;
      while (row[end + 1] === ch) end += 1;
      const run = `M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`;
      if (ch === "+") accent += run;
      else ink += run;
      x = end + 1;
    }
  });
  const paths = { ink, accent };
  cache.set(name, paths);
  return paths;
}

export function PixelIcon({ name, size = 16, title, ...rest }: PixelIconProps) {
  const { ink, accent } = pixelPaths(name);
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 16 16"
      width={size}
      height={size}
      fill="currentColor"
      shapeRendering="crispEdges"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
      data-icon={name}
      {...rest}
    >
      {title && <title>{title}</title>}
      {ink && <path d={ink} />}
      {accent && <path d={accent} fill={ACCENT} />}
    </svg>
  );
}
