export type PixelIconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  name: PixelIconName;
  /** 寬高，預設 16；用 16 的整數倍最銳利 */
  size?: number | string;
  /** 提供時圖示會被讀出；不提供時視為裝飾，aria-hidden */
  title?: string;
  /** ink（預設）：全部墨色。pigment：物件本色，一個畫面只選一種 */
  tone?: PixelTone;
  /** 指定顏色，覆蓋 pixelPigments（例如寶石依稀有度換色）；傳了就視為 pigment */
  pigment?: Pigment;
};

const ACCENT = "var(--sunui-icon-accent, currentColor)";
const SHINE = "var(--sunui-pixel-shine, #fff)";

/** 每種字元的上色方式；順序就是繪製順序 */
export const pixelTones = [
  { char: "=", fill: "currentColor", opacity: 0.3 },
  { char: ":", fill: "currentColor", opacity: 0.58 },
  { char: "-", fill: "currentColor", opacity: 0.3 },
  { char: "_", fill: "currentColor", opacity: 0.58 },
  { char: "~", fill: ACCENT, opacity: 0.62 },
  { char: "+", fill: ACCENT, opacity: 1 },
  { char: "i", fill: "currentColor", opacity: 0.5 },
  { char: "o", fill: "currentColor", opacity: 0.85 },
  { char: "#", fill: "currentColor", opacity: 1 },
  { char: "*", fill: SHINE, opacity: 1 },
] as const;

type PixelToneList = readonly { char: string; fill: string; opacity: number }[];
const pigmentToneCache = new Map<string, PixelToneList>();

/** pigment 模式下一個圖示的用色：主體、accent（+ ~）、第二材質（- _） */
export type PixelPalette = { pigment: Pigment; accent?: Pigment; second?: Pigment };

const shift = (base: string, [dL, kC, dH]: Step) => `oklch(from ${base} calc(l + ${dL}) calc(c * ${kC}) calc(h + ${dH}))`;

/**
 * pigment 版的上色：外框與亮點不變；填色、陰影、accent 都是不透明的本色色階，
 * 同一個圖示在亮、暗紙上顏色一致（半透明會吃到底色而發灰）。
 * 覆寫 --sunui-pigment-<name> 時，整條色階跟著它推算。
 */
export function pigmentTones(pigment: Pigment, accent: Pigment = pigment, second: Pigment = pigment): PixelToneList {
  const key = `${pigment}/${accent}/${second}`;
  let hit = pigmentToneCache.get(key);
  if (!hit) {
    const v = (p: Pigment) => `var(--sunui-pigment-${p}, ${pigments[p]})`;
    const base = v(pigment);
    const r = ramps[pigment];
    hit = [
      { char: "=", fill: shift(base, r.light), opacity: 1 },
      { char: ":", fill: shift(base, r.shade), opacity: 1 },
      { char: "-", fill: shift(v(second), ramps[second].light), opacity: 1 },
      { char: "_", fill: shift(v(second), ramps[second].shade), opacity: 1 },
      { char: "~", fill: shift(v(accent), ramps[accent].deep), opacity: 1 },
      { char: "+", fill: v(accent), opacity: 1 },
      // 亮色紙：外框用本色最深一階混一點墨，線條有顏色、份量變輕。
      // 暗色紙（color-scheme: dark）：深色外框會消失，改回墨色。混進 currentColor 是保險，沒設 color-scheme 的暗底也看得到
      { char: "i", fill: shift(base, r.deep), opacity: 1 },
      { char: "o", fill: `light-dark(color-mix(in oklch, ${shift(base, r.deep)} 65%, currentColor), currentColor)`, opacity: 1 },
      { char: "#", fill: "currentColor", opacity: 1 },
      { char: "*", fill: SHINE, opacity: 1 },
    ];
    pigmentToneCache.set(key, hit);
  }
  return hit;
}

/** 依 tone 與圖示名稱決定要用的顏色；回傳 undefined 代表墨色 */
export function resolvePigment(name: string, tone?: PixelTone, pigment?: Pigment): Pigment | undefined {
  if (pigment) return pigment;
  if (tone !== "pigment") return undefined;
  return pixelPigments[name as PixelIconName];
}

/** 同 resolvePigment，再補上這個圖示的 accent 與第二材質 */
export function resolvePalette(name: string, tone?: PixelTone, pigment?: Pigment): PixelPalette | undefined {
  const main = resolvePigment(name, tone, pigment);
  if (!main) return undefined;
  const extra = pixelPalettes[name as PixelIconName];
  // 指定了 pigment 但 accent 沒有另外設定時，accent 跟著指定色（寶石換稀有度）
  return { pigment: main, accent: extra?.accent, second: extra?.second };
}

export type PixelPaths = Record<string, string>;

const FILLED = /[=:~+*\-_]/;

/**
 * 把「#」分成三種：
 * - 「o」邊：碰到任何空格（外部或中間的孔）。比內部的記號淡一點（墨色 85%）。
 * - 「i」內線：被填色包圍、只有 1 格粗的線（寶石切面、火焰分層、盾牌與箱子的分隔線）。畫成比邊更淡的線，
 *   否則線會比外框還黑，圖示中間像多了一條裂縫。
 * - 「#」記號：至少 2 × 2 的墨色塊（驚嘆號、骰子點、眼珠）。這是符號本身，維持全墨。
 * 只有外框沒有填色的控制符號（勾、叉、箭頭）不拆，維持全墨。
 */
function markOuter(rows: readonly string[]): string[] {
  if (!rows.some((r) => FILLED.test(r))) return [...rows];
  const h = rows.length;
  const w = rows[0]?.length ?? 0;
  const at = (x: number, y: number) => (x < 0 || y < 0 || x >= w || y >= h ? "." : rows[y][x]);
  const ink = (x: number, y: number) => at(x, y) === "#";
  const block = (x: number, y: number) => ink(x, y) && ink(x + 1, y) && ink(x, y + 1) && ink(x + 1, y + 1);
  return rows.map((r, y) =>
    Array.from(r, (c, x) => {
      if (c !== "#") return c;
      if (at(x, y - 1) === "." || at(x - 1, y) === "." || at(x, y + 1) === "." || at(x + 1, y) === ".") return "o";
      if (block(x, y) || block(x - 1, y) || block(x, y - 1) || block(x - 1, y - 1)) return "#";
      return "i";
    }).join(""),
  );
}

/** 把點陣轉成每種字元一條路徑：同一列相鄰的同色格合併成一段，路徑短、縮放不留縫。origin 是左上角的座標偏移 */
export function toPixelPaths(source: readonly string[], origin = 0): PixelPaths {
  const rows = markOuter(source);
  const paths: PixelPaths = {};
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x;
      while (row[end + 1] === ch) end += 1;
      if (ch !== ".") paths[ch] = (paths[ch] ?? "") + `M${x + origin} ${y + origin}h${end - x + 1}v1h-${end - x + 1}z`;
      x = end + 1;
    }
  });
  return paths;
}

const cache = new Map<string, PixelPaths>();
export function pixelPaths(name: PixelIconName) {
  let hit = cache.get(name);
  if (!hit) {
    hit = toPixelPaths(pixelIcons[name]);
    cache.set(name, hit);
  }
  return hit;
}

export function PixelPathsGroup({ paths, pigment, palette }: { paths: PixelPaths; pigment?: Pigment; palette?: PixelPalette }) {
  const main = palette?.pigment ?? pigment;
  const tones: PixelToneList = main ? pigmentTones(main, palette?.accent, palette?.second) : pixelTones;
  return (
    <>
      {tones.map(({ char, fill, opacity }) =>
        paths[char] ? (
          <path key={char} d={paths[char]} fill={fill} fillOpacity={opacity === 1 ? undefined : opacity} />
        ) : null,
      )}
    </>
  );
}

export function PixelIcon({ name, size = 16, title, tone, pigment, ...rest }: PixelIconProps) {
  const palette = resolvePalette(name, tone, pigment);
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
      data-icon={name}
      data-tone={palette ? "pigment" : undefined}
      {...rest}
    >
      {title && <title>{title}</title>}
      <PixelPathsGroup paths={pixelPaths(name)} palette={palette} />
    </svg>
  );
}
